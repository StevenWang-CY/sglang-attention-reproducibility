#!/usr/bin/env python3
"""
Create hierarchical HTML tree visualization of attention weights.
Groups tokens by attention weight ranges and semantic structure.
"""
import argparse
import csv
import json
import re
from pathlib import Path
from typing import List, Dict, Any, Tuple
from collections import defaultdict


def parse_token_mapping(token_map_file: Path) -> List[str]:
    """
    Parse token mapping CSV file generated by translate_tokens.py.

    CSV format:
    row_index,token_id,token_text
    0,8948,system
    1,527,You
    2,35,>\n
    ...

    Token text is escaped (e.g., \\n instead of actual newline).
    This function un-escapes them.

    Returns list of token texts in row order.
    """
    print(f"Reading token mapping from: {token_map_file}")

    tokens = []

    with open(token_map_file, 'r', encoding='utf-8') as f:
        reader = csv.reader(f)
        header = next(reader)  # Skip header

        for row in reader:
            if not row or len(row) < 3:
                continue

            # row_index, token_id, token_text (escaped)
            row_idx = int(row[0])
            escaped_text = row[2]

            # Un-escape the text by using codecs.decode with 'unicode_escape'
            # This converts \\n back to \n, \\t back to \t, etc.
            try:
                # For Python 3, we need to handle this carefully
                # The text is already a string with escaped sequences like '\\n'
                # We need to decode it properly
                import codecs
                token_text = codecs.decode(escaped_text, 'unicode_escape')
            except Exception:
                # If un-escaping fails, use as-is
                token_text = escaped_text

            tokens.append(token_text)

    print(f"Loaded {len(tokens)} tokens from mapping file")
    return tokens


def read_attention_weights(csv_file: Path) -> Tuple[List[int], List[List[float]]]:
    """Read attention weights from CSV."""
    print(f"Reading attention weights from: {csv_file}")

    token_ids = []
    attention_matrix = []

    with open(csv_file, 'r') as f:
        reader = csv.reader(f)
        next(reader)  # Skip header

        for row in reader:
            if not row:
                continue
            token_id = int(row[0])
            weights = [float(w) for w in row[1:] if w]

            token_ids.append(token_id)
            attention_matrix.append(weights)

    print(f"Read attention weights for {len(token_ids)} tokens")
    return token_ids, attention_matrix


def build_hierarchical_tree(
    tokens: List[str],
    token_ids: List[int],
    attention_matrix: List[List[float]],
    focus_token_idx: int = -1,
    min_weight: float = 0.0001,
    show_all_tokens: bool = False
) -> Dict[str, Any]:
    """
    Build hierarchical tree structure grouped by attention weight ranges.
    This creates a flame-graph-like structure.

    Args:
        show_all_tokens: If True, show all tokens regardless of min_weight threshold
    """
    if focus_token_idx < 0:
        focus_token_idx = len(token_ids) + focus_token_idx

    if focus_token_idx >= len(attention_matrix):
        raise ValueError(f"Focus token index {focus_token_idx} out of range")

    attention_weights = attention_matrix[focus_token_idx]

    def get_token_text(idx: int) -> str:
        if idx < len(tokens):
            text = tokens[idx]
            # Truncate very long tokens
            if len(text) > 50:
                text = text[:47] + "..."
            return text
        return f"<tok_{token_ids[idx] if idx < len(token_ids) else idx}>"

    # Define attention weight tiers for grouping
    tiers = [
        ("Very High (>0.1)", 0.1, float('inf')),
        ("High (0.01-0.1)", 0.01, 0.1),
        ("Medium (0.001-0.01)", 0.001, 0.01),
        ("Low (0.0001-0.001)", 0.0001, 0.001),
        ("Very Low (<0.0001)", 0, 0.0001),
    ]

    # Group tokens by tier
    tier_groups = defaultdict(list)

    for i, weight in enumerate(attention_weights):
        if i >= len(token_ids):
            continue

        # Skip low-weight tokens unless show_all_tokens is enabled
        if not show_all_tokens and weight < min_weight:
            continue

        token_text = get_token_text(i)

        # Find tier
        for tier_name, tier_min, tier_max in tiers:
            if tier_min <= weight < tier_max:
                tier_groups[tier_name].append({
                    "name": token_text,
                    "value": weight,
                    "token_idx": i,
                    "token_id": token_ids[i] if i < len(token_ids) else -1,
                })
                break

    # Build root node
    focus_text = get_token_text(focus_token_idx)
    root = {
        "name": f"Query: {focus_text}",
        "value": 1.0,
        "children": []
    }

    # Create tier nodes
    for tier_name, tier_min, tier_max in tiers:
        if tier_name not in tier_groups or not tier_groups[tier_name]:
            continue

        tokens_in_tier = tier_groups[tier_name]
        # Sort by attention weight descending
        tokens_in_tier.sort(key=lambda x: x["value"], reverse=True)

        total_weight = sum(t["value"] for t in tokens_in_tier)

        tier_node = {
            "name": f"{tier_name} ({len(tokens_in_tier)} tokens, Σ={total_weight:.4f})",
            "value": total_weight,
            "children": tokens_in_tier
        }

        root["children"].append(tier_node)

    return root


