def main():
    parser = argparse.ArgumentParser(
        description='Generate hierarchical tree visualization of attention weights',
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Examples:
  # Basic usage - output: {csv_name}_focus8641_viz.html (last token by default)
  python visualize_attention_hierarchical.py \\
      --csv attn_weights_request_000001_layer_00_head_00.csv \\
      --tokens attn_weights_request_000001_layer_00_head_00_tokens.csv \\
      --layer 0 --head 0

  # Show ALL tokens - output: {csv_name}_focus8641_all_tokens_viz.html
  python visualize_attention_hierarchical.py \\
      --csv attn_weights.csv \\
      --tokens attn_weights_tokens.csv \\
      --show-all

  # Specific token - output: {csv_name}_focus1000_viz.html
  python visualize_attention_hierarchical.py \\
      --csv attn_weights.csv \\
      --tokens attn_weights_tokens.csv \\
      --focus-token 1000

  # Custom output location (override auto-generation)
  python visualize_attention_hierarchical.py \\
      --csv attn_weights.csv \\
      --tokens attn_weights_tokens.csv \\
      --output /custom/path/my_viz.html
        """
    )

    parser.add_argument('--csv', required=True, help='Path to CSV file with attention weights')
    parser.add_argument('--tokens', required=True, help='Path to token mapping CSV file (generated by translate_tokens.py)')
    parser.add_argument('--output', default=None, help='Output HTML file (default: auto-generate in same dir as CSV)')
    parser.add_argument('--focus-token', type=int, default=-1, help='Token index to focus on (-1 for last)')
    parser.add_argument('--min-weight', type=float, default=0.0001, help='Minimum attention weight to include')
    parser.add_argument('--show-all', action='store_true', help='Show all tokens regardless of min-weight threshold')
    parser.add_argument('--layer', type=int, default=0, help='Layer number (for display)')
    parser.add_argument('--head', type=int, default=0, help='Head number (for display)')

    args = parser.parse_args()

    csv_file = Path(args.csv)
    token_map_file = Path(args.tokens)

    if not csv_file.exists():
        print(f"Error: CSV file not found: {csv_file}")
        return 1

    if not token_map_file.exists():
        print(f"Error: Token mapping file not found: {token_map_file}")
        return 1

    tokens = parse_token_mapping(token_map_file)
    token_ids, attention_matrix = read_attention_weights(csv_file)

    # Calculate actual focus token index (resolve negative indices)
    focus_token_idx = args.focus_token
    if focus_token_idx < 0:
        focus_token_idx = len(token_ids) + focus_token_idx

    # Auto-generate output filename if not specified
    if args.output is None:
        # Get CSV file stem (e.g., "attn_weights_request_000001_layer_00_head_00")
        csv_stem = csv_file.stem

        # Add focus token index to filename
        focus_suffix = f"_focus{focus_token_idx}"

        # Add mode suffix
        if args.show_all:
            mode_suffix = "_all_tokens"
        else:
            mode_suffix = ""

        # Combine: {csv_stem}_focus{idx}[_all_tokens]_viz.html
        output_file = csv_file.parent / f"{csv_stem}{focus_suffix}{mode_suffix}_viz.html"
    else:
        output_file = Path(args.output)

    print(f"Building hierarchical tree for token index {args.focus_token}...")
    if args.show_all:
        print("  Note: --show-all enabled, displaying ALL tokens regardless of weight")
    hierarchy = build_hierarchical_tree(
        tokens,
        token_ids,
        attention_matrix,
        args.focus_token,
        args.min_weight,
        args.show_all
    )

    generate_html_hierarchical(
        hierarchy,
        output_file,
        args.layer,
        args.head,
        args.focus_token if args.focus_token >= 0 else len(token_ids) + args.focus_token
    )

    print(f"\nDone! Open {output_file} in your browser to view the visualization.")
    print(f"Total tiers: {len(hierarchy.get('children', []))}")

    return 0


if __name__ == '__main__':
    exit(main())
